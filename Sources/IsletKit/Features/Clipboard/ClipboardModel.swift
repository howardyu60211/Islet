import AppKit
import Observation

/// 剪貼簿紀錄：記下最近複製的文字、連結、圖片與檔案，點一下就能再複製一次。
/// 只存在記憶體裡，結束 App 就清掉；密碼管理器標示為「隱藏」的內容不會記錄。
@Observable
final class ClipboardModel {
    struct Item: Identifiable {
        enum Preview {
            case text(String)
            case link(URL)
            case image(NSImage)
            case files([URL])
        }

        let id = UUID()
        let preview: Preview
        /// 原本剪貼簿上的每一筆內容與所有格式，再複製時原樣放回去（保留格式、圖片原檔）。
        let representations: [[NSPasteboard.PasteboardType: Data]]
        let sourceApp: String?
        let sourceBundleIdentifier: String?
        let date: Date
        /// 判斷是否重複用。
        let signature: String

        /// 佔用的記憶體（所有格式的資料加起來）。
        var byteCount: Int {
            representations.reduce(0) { total, representation in
                total + representation.values.reduce(0) { $0 + $1.count }
            }
        }

        /// 收合時動畫用的摘要。
        var summary: ClipboardSummary {
            switch preview {
            case .text(let string):
                ClipboardSummary(id: id, kind: .text, excerpt: string.trimmingCharacters(in: .whitespacesAndNewlines), image: nil)
            case .link(let url):
                ClipboardSummary(id: id, kind: .link, excerpt: url.host ?? url.absoluteString, image: nil)
            case .image(let image):
                ClipboardSummary(id: id, kind: .image, excerpt: "", image: image)
            case .files(let urls):
                ClipboardSummary(id: id, kind: .files(count: urls.count), excerpt: urls[0].lastPathComponent, image: nil)
            }
        }
    }

    static let maxItems = 30
    /// 超過這個大小的內容（例如很大的圖片）不記錄。
    static let maxBytes = 20 * 1024 * 1024
    /// 整個紀錄最多佔用的記憶體；超過就從最舊的開始丟（最新的一筆一定保留）。
    static let maxTotalBytes = 32 * 1024 * 1024

    /// 密碼管理器等 App 用來標示「不要記錄」的格式（http://nspasteboard.org）。
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// 最新的在前面。
    private(set) var items: [Item] = []
    /// 剛從紀錄裡複製的項目（顯示「已複製」）。
    private(set) var recentlyCopiedID: UUID?
    private(set) var appIcons: [String: NSImage] = [:]

    /// 偵測到新的拷貝或剪下時呼叫（啟動時剪貼簿上原本的內容不算）。
    @ObservationIgnored var onCapture: (Item) -> Void = { _ in }

    @ObservationIgnored private let pasteboard: NSPasteboard
    @ObservationIgnored private var changeCount: Int
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var copiedResetTask: Task<Void, Never>?

    /// 剪貼簿沒有變更通知，只能定時檢查 changeCount（很便宜）。
    private static let pollInterval: TimeInterval = 0.5

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        changeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        // 啟動時剪貼簿上的內容也記下來
        changeCount = -1
        checkForChanges(notify: false)
        let timer = Timer(timeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.checkForChanges() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func checkForChanges(notify: Bool = true) {
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        let source = NSWorkspace.shared.frontmostApplication
        guard let item = Self.capture(pasteboard, sourceApp: source?.localizedName, sourceBundleIdentifier: source?.bundleIdentifier) else { return }
        insert(item)
        if notify {
            onCapture(item)
        }
    }

    // MARK: - 動作

    /// 放回剪貼簿，並移到最前面。
    func copy(_ item: Item) {
        pasteboard.clearContents()
        let pasteboardItems = item.representations.map { representation in
            let pasteboardItem = NSPasteboardItem()
            for (type, data) in representation {
                pasteboardItem.setData(data, forType: type)
            }
            return pasteboardItem
        }
        pasteboard.writeObjects(pasteboardItems)
        // 自己寫進去的不要再記一次
        changeCount = pasteboard.changeCount
        if let index = items.firstIndex(where: { $0.id == item.id }), index > 0 {
            items.insert(items.remove(at: index), at: 0)
        }
        recentlyCopiedID = item.id
        copiedResetTask?.cancel()
        copiedResetTask = Task { [weak self] in
            try? await Task.sleep(for: .seconds(1.2))
            guard !Task.isCancelled else { return }
            self?.recentlyCopiedID = nil
        }
    }

    func remove(_ item: Item) {
        items.removeAll { $0.id == item.id }
    }

    func removeAll() {
        items.removeAll()
    }

    func revealInFinder(_ item: Item) {
        guard case .files(let urls) = item.preview else { return }
        NSWorkspace.shared.activateFileViewerSelecting(urls)
    }

    // MARK: - 內部

    func insert(_ item: Item) {
        items.removeAll { $0.signature == item.signature }
        items.insert(item, at: 0)
        if items.count > Self.maxItems {
            items.removeLast(items.count - Self.maxItems)
        }
        var total = items.reduce(0) { $0 + $1.byteCount }
        while total > Self.maxTotalBytes, items.count > 1 {
            total -= items.removeLast().byteCount
        }
        if let bundleID = item.sourceBundleIdentifier, appIcons[bundleID] == nil,
           let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID) {
            appIcons[bundleID] = NSWorkspace.shared.icon(forFile: url.path).bitmapCopy(pointSize: 16)
        }
    }

    /// 把剪貼簿目前的內容變成一個項目；沒有認得的內容、被標示為隱藏或太大時回傳 nil。
    static func capture(_ pasteboard: NSPasteboard, sourceApp: String?, sourceBundleIdentifier: String?) -> Item? {
        let types = pasteboard.types ?? []
        guard !types.isEmpty, !types.contains(where: { ignoredTypes.contains($0.rawValue) }) else { return nil }

        var representations: [[NSPasteboard.PasteboardType: Data]] = []
        var totalBytes = 0
        for pasteboardItem in pasteboard.pasteboardItems ?? [] {
            var representation: [NSPasteboard.PasteboardType: Data] = [:]
            for type in pasteboardItem.types {
                guard let data = pasteboardItem.data(forType: type) else { continue }
                totalBytes += data.count
                guard totalBytes <= maxBytes else { return nil }
                representation[type] = data
            }
            if !representation.isEmpty {
                representations.append(representation)
            }
        }
        guard !representations.isEmpty, let (preview, signature) = makePreview(pasteboard) else { return nil }
        return Item(
            preview: preview,
            representations: representations,
            sourceApp: sourceApp,
            sourceBundleIdentifier: sourceBundleIdentifier,
            date: Date(),
            signature: signature
        )
    }

    private static func makePreview(_ pasteboard: NSPasteboard) -> (Item.Preview, String)? {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return (.files(urls), "files:" + urls.map(\.path).joined(separator: "\n"))
        }
        if let string = pasteboard.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            if !trimmed.contains(where: \.isWhitespace), let url = URL(string: trimmed), let scheme = url.scheme?.lowercased(),
               ["http", "https"].contains(scheme), url.host != nil {
                return (.link(url), "text:" + string)
            }
            return (.text(string), "text:" + string)
        }
        if let image = NSImage(pasteboard: pasteboard), let thumbnail = image.thumbnail(maxSide: 160) {
            let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) ?? Data()
            return (.image(thumbnail), "image:\(data.count):\(data.hashValue)")
        }
        return nil
    }
}

extension NSImage {
    /// 等比例縮小成長邊不超過 maxSide 的點陣圖（顯示用，避免一直重畫大圖）。
    func thumbnail(maxSide: CGFloat, scale: CGFloat = 2) -> NSImage? {
        guard size.width > 0, size.height > 0 else { return nil }
        let ratio = min(1, maxSide / max(size.width, size.height))
        let target = NSSize(width: max(1, (size.width * ratio).rounded()), height: max(1, (size.height * ratio).rounded()))
        guard let bitmap = NSBitmapImageRep(
            bitmapDataPlanes: nil,
            pixelsWide: Int(target.width * scale),
            pixelsHigh: Int(target.height * scale),
            bitsPerSample: 8,
            samplesPerPixel: 4,
            hasAlpha: true,
            isPlanar: false,
            colorSpaceName: .deviceRGB,
            bytesPerRow: 0,
            bitsPerPixel: 0
        ) else { return nil }
        bitmap.size = target
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: bitmap)
        NSGraphicsContext.current?.imageInterpolation = .high
        draw(in: NSRect(origin: .zero, size: target), from: .zero, operation: .copy, fraction: 1)
        NSGraphicsContext.restoreGraphicsState()
        let image = NSImage(size: target)
        image.addRepresentation(bitmap)
        return image
    }
}

/// 拷貝／剪下時收合動畫顯示的內容。
struct ClipboardSummary: Equatable {
    enum Kind: Equatable {
        case text
        case link
        case image
        case files(count: Int)
    }

    let id: UUID
    let kind: Kind
    let excerpt: String
    /// 圖片的縮圖（已經縮小過，不是原圖）。
    let image: NSImage?
}
